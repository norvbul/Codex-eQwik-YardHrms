import { format } from 'prettier';
import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import {
  registerSchema,
  loginSchema,
  employeeSchema,
  companySchema,
  leaveSchema,
  timesheetSchema,
  overtimeSchema,
} from '../packages/types/src/index.js';
const publicPaths = new Set([
  '/health',
  '/auth/register',
  '/auth/login',
  '/auth/verify-email',
  '/auth/resend-verification',
  '/auth/forgot-password',
  '/auth/reset-password',
]);
const contracts: Record<string, z.ZodType> = {
  'post /auth/register': registerSchema,
  'post /auth/login': loginSchema,
  'post /employees': employeeSchema,
  'patch /tenants/current': companySchema,
  'post /leave-requests': leaveSchema,
  'post /timesheets': timesheetSchema,
  'post /overtime': overtimeSchema,
};
const paths: Record<string, Record<string, unknown>> = {};
function add(method: string, path: string) {
  if (path === '/api/v1/openapi.json') return;
  if (path.startsWith('/api/v1')) path = path.slice(7);
  const openPath = path.replace(/:([A-Za-z]+)/g, '{$1}'),
    isPublic = publicPaths.has(path),
    schema = contracts[method + ' ' + path];
  paths[openPath] ||= {};
  paths[openPath][method] = {
    summary: method.toUpperCase() + ' ' + openPath,
    tags: [path.startsWith('/platform') ? 'Qwik platform' : path.split('/')[1]],
    security: isPublic
      ? []
      : [method === 'get' ? { sessionCookie: [] } : { sessionCookie: [], csrfHeader: [] }],
    parameters: [...openPath.matchAll(/\{(\w+)\}/g)].map((m) => ({
      name: m[1],
      in: 'path',
      required: true,
      schema: { type: 'string' },
    })),
    ...(schema
      ? {
          requestBody: {
            required: true,
            content: {
              'application/json': {
                schema: z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any' }),
              },
            },
          },
        }
      : {}),
    responses: {
      '200': {
        description:
          'Success. JSON uses a data envelope; download routes return private file bytes.',
      },
      ...(method === 'post'
        ? { '201': { description: 'Created' }, '202': { description: 'Background job accepted' } }
        : {}),
      '401': { description: 'Authentication or active session required' },
      '403': { description: 'Role, tenant scope, MFA or entitlement denied' },
      '404': { description: 'Record absent in authorized scope' },
      '409': { description: 'State, version, one-use or capacity conflict' },
      '422': { description: 'Validation; error.issues contains field paths' },
      '429': { description: 'Distributed request or authentication rate limit' },
    },
  };
}
for (const file of [
  'app',
  'identity',
  'foundation',
  'employees',
  'master-data',
  'configuration-review',
  'leave',
  'time',
  'imports',
  'reports',
  'files',
  'payroll',
  'payslips',
  'licensing',
  'platform',
]) {
  const source = readFileSync('apps/api/src/' + file + '.ts', 'utf8');
  for (const m of source.matchAll(/\w+\.(get|post|patch|delete)\(\s*'([^']+)'\s*,/g))
    add(m[1]!, m[2]!);
}
for (const type of ['timesheets', 'overtime']) add('post', '/' + type + '/:id/withdraw');
const spec = {
  openapi: '3.1.0',
  info: {
    title: 'eQwik YardHRMS API',
    version: '0.1.0',
    description:
      'Tenant-session authorization and separate Qwik platform authority. Mutations require the session CSRF header and an allowed browser Origin. Decimal monetary values use strings. MFA is mandatory for privileged accounts. Payroll compliance mode TEST_ONLY cannot disburse real funds.',
  },
  servers: [{ url: '/api/v1' }],
  components: {
    securitySchemes: {
      sessionCookie: { type: 'apiKey', in: 'cookie', name: 'yard_session' },
      csrfHeader: { type: 'apiKey', in: 'header', name: 'x-csrf-token' },
    },
  },
  paths,
};
writeFileSync(
  'apps/api/src/openapi.ts',
  await format(
    '// Generated by npm run api:docs from implemented routes and shared validation contracts.\nexport const apiSpecification = ' +
      JSON.stringify(spec, null, 2) +
      ';\n',
    { parser: 'typescript', singleQuote: true, trailingComma: 'all', printWidth: 100, tabWidth: 2 },
  ),
);
console.log(
  'Documented ' +
    Object.values(paths).reduce((n, p) => n + Object.keys(p).length, 0) +
    ' implemented operations.',
);
